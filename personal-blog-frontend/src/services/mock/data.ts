/** 生成可被前端消费的文章数据（列表 + 详情） */
function buildArticles(): ArticleDetail[] {
  return seeds.map(seed => {
    const category = mockCategories.find(c => c.id === seed.categoryId)!
    const tags = mockTags.filter(t => seed.tagIds.includes(t.id))
    return {
      id: seed.id,
      title: seed.title,
      summary: seed.summary,
      category,
      tags,
      author: { id: 1, name: '管理员' },
      views: seed.views,
      likes: seed.likes,
      liked: false,
      createdAt: seed.createdAt,
      updatedAt: seed.createdAt,
      published: true,
      content: seed.content,
    }
  })
}

/** 可变的文章数据（支持 Mock 中的增删改） */
export const mockArticles: ArticleDetail[] = buildArticles()

/** 计算分类/标签的真实文章数 */
export function categoriesWithCount(): CategoryInfo[] {
  return mockCategories.map(c => ({
    ...c,
    count: mockArticles.filter(a => a.category.id === c.id).length,
  }))
}

export function tagsWithCount(): TagInfo[] {
  return mockTags.map(t => ({
    ...t,
    count: mockArticles.filter(a => a.tags.some(tag => tag.id === t.id)).length,
  }))
}
